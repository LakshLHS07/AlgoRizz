def get_criteria_translations(lang: str = "en") -> dict:
    return CRITERIA_TRANSLATIONS.get(lang) or CRITERIA_TRANSLATIONS.get("hi") or CRITERIA_TRANSLATIONS["en"]

def localize_scheme_dict(scheme_data: dict, lang: str = "en") -> dict:
    if lang == "en":
        return scheme_data
    scheme_id = scheme_data.get("id")
    trans_map = SCHEME_TRANSLATIONS.get(scheme_id, {})
    trans = trans_map.get(lang) or trans_map.get("hi")
    if not trans:
        return scheme_data
    
    localized = dict(scheme_data)
    localized["name"] = trans.get("name", scheme_data.get("name"))
    localized["category"] = trans.get("category", scheme_data.get("category"))
    localized["ministry"] = trans.get("ministry", scheme_data.get("ministry"))
    localized["benefitAmount"] = trans.get("benefitAmount", scheme_data.get("benefitAmount"))
    localized["targetGroup"] = trans.get("targetGroup", scheme_data.get("targetGroup"))
    localized["summary"] = trans.get("summary", scheme_data.get("summary"))
    return localized
