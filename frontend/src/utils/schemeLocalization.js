// Helper function to get fully localized scheme object based on selected language
export function getLocalizedScheme(scheme, lang = 'en') {
  if (!scheme) return null;
  if (lang === 'en') return scheme;

  const schemeTransMap = SCHEME_TRANSLATIONS[scheme.id];
  // Check exact language or fall back to Hindi for other Indian regional languages if specific string not defined
  const trans = schemeTransMap ? (schemeTransMap[lang] || schemeTransMap['hi']) : null;

  if (!trans) return scheme;

  return {
    ...scheme,
    name: trans.name || scheme.name,
    category: trans.category || scheme.category,
    ministry: trans.ministry || scheme.ministry,
    benefitAmount: trans.benefitAmount || scheme.benefitAmount,
    targetGroup: trans.targetGroup || scheme.targetGroup,
    targetAudience: trans.targetGroup || scheme.targetAudience,
    summary: trans.summary || scheme.summary,
    applicationMode: trans.applicationMode || scheme.applicationMode
  };
}
