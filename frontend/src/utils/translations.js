// Fallback helper to safely retrieve translation with complete English fallback
export function getTranslation(lang = 'en') {
  const english = TRANSLATIONS['en'];
  const target = TRANSLATIONS[lang] || TRANSLATIONS['hi'] || english;
  return { ...english, ...target };
}

// Helper to translate occupation strings
