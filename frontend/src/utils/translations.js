// Fallback helper to safely retrieve translation with complete English fallback
export function getTranslation(lang = 'en') {
  const english = TRANSLATIONS['en'];
  if (lang === 'en') return { ...english };
  const hindi = TRANSLATIONS['hi'] || {};
  const target = TRANSLATIONS[lang] || {};
  return { ...english, ...hindi, ...target };
}

// Helper to translate occupation strings
export function translateOccupation(occ, lang = 'en') {
  if (!occ) return "";
  if (lang === 'en') return occ;
  const item = OCCUPATION_LABELS[occ] || OCCUPATION_LABELS[occ.toLowerCase()];
  if (item && item[lang]) return item[lang];
  if (item && item['hi']) return item['hi'];
  return occ;
}

